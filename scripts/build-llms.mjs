#!/usr/bin/env node
/**
 * Builds llms-full.txt: every human doc in one file, for AI assistants
 * (https://llmstxt.org). llms.txt (the index) is written by hand.
 *
 *   node scripts/build-llms.mjs        (npm run docs:llms)
 *
 * Order: README, AGENTS, then docs/*.md in a fixed reading order, then the
 * skill and its references. No dependencies.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ORDER = [
  'README.md',
  'AGENTS.md',
  'docs/GLOSSARY.md',
  'docs/ARCHITECTURE.md',
  'docs/INTEGRATION.md',
  'docs/WRITING_CARDS.md',
  'docs/PLAYGROUND.md',
  'docs/AI_DEMO.md',
  'docs/TESTING.md',
  'docs/CI_CD.md',
  'docs/FAQ.md',
  'docs/TROUBLESHOOTING.md',
  'skills/vue-mcp-apps/SKILL.md',
  'skills/vue-mcp-apps/references/api.md',
  'skills/vue-mcp-apps/references/protocol.md',
  'SECURITY.md',
  'CHANGELOG.md',
]

// Any other docs/*.md not listed above, so a new doc is never silently left out.
const extra = readdirSync(join(root, 'docs'))
  .filter(f => f.endsWith('.md'))
  .map(f => `docs/${f}`)
  .filter(f => !ORDER.includes(f))
  .sort()

const files = [...ORDER, ...extra].filter(f => existsSync(join(root, f)))
const parts = [
  '# vue-mcp-apps — full documentation',
  '',
  '> Write MCP Apps (the io.modelcontextprotocol/ui extension) as native Vue components, run them natively and sandboxed, and test them in a three-layer playground with an in-browser AI demo. Repository: https://github.com/JuanmanDev/vue-mcp-apps',
  '',
  `Generated by scripts/build-llms.mjs from ${files.length} files. Do not edit by hand.`,
  '',
]
for (const file of files) {
  const text = readFileSync(join(root, file), 'utf8').replace(/\r\n/g, '\n').trim()
  parts.push(`\n\n================================================================================\nFILE: ${relative(root, join(root, file)).split('\\').join('/')}\n================================================================================\n\n${text}`)
}
writeFileSync(join(root, 'llms-full.txt'), `${parts.join('\n')}\n`, 'utf8')
console.log(`llms-full.txt: ${files.length} files, ${(parts.join('\n').length / 1024).toFixed(0)} kB`)
